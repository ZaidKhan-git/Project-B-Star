class OrbitalPropagator:
    """
    Propagates satellite orbits using SGP4 and correlates with space weather.
    
    SGP4 (Simplified General Perturbations 4) is the standard algorithm
    for predicting satellite positions from TLE elements.
    
    Attributes:
        db_path: Path to SQLite database with TLE and Kp data
    """
    
    # Earth's equatorial radius in kilometers
    EARTH_RADIUS_KM = 6378.137
    
    def __init__(self, db_path: str = "satellite_data.db"):
        """
        Initialize the Orbital Propagator.
        
        Args:
            db_path: SQLite database file path with TLE and Kp data
        """
        self.db_path = db_path
    
    def _parse_tle_to_satrec(self, tle_line1: str, tle_line2: str) -> Optional[Satrec]:
        """
        Parse TLE lines into SGP4 Satrec object.
        
        Args:
            tle_line1: First line of TLE
            tle_line2: Second line of TLE
            
        Returns:
            Satrec object for propagation, or None if parsing fails
        """
        try:
            satellite = Satrec.twoline2rv(tle_line1, tle_line2)
            return satellite
        except Exception as e:
            logger.warning(f"Failed to parse TLE: {e}")
            return None
    
    def calculate_altitude(
        self, 
        satellite: Satrec, 
        dt: datetime
    ) -> Optional[float]:
        """
        Calculate satellite altitude at a specific datetime.
        
        Uses SGP4 propagation to get position vector, then calculates
        distance from Earth center minus Earth radius.
        
        Args:
            satellite: Satrec object from TLE
            dt: Datetime for position calculation
            
        Returns:
            Altitude in kilometers, or None if propagation fails
        """
        try:
            # Convert datetime to Julian date
            jd, fr = jday(
                dt.year, dt.month, dt.day,
                dt.hour, dt.minute, dt.second + dt.microsecond / 1e6
            )
            
            # Propagate to get position and velocity
            error_code, position, velocity = satellite.sgp4(jd, fr)
            
            if error_code != 0:
                return None
            
            # Calculate distance from Earth center
            x, y, z = position
            distance_km = np.sqrt(x**2 + y**2 + z**2)
            
            # Altitude = distance - Earth radius
            altitude_km = distance_km - self.EARTH_RADIUS_KM
            
            return altitude_km
            
        except Exception as e:
            logger.warning(f"Altitude calculation failed: {e}")
            return None
    
    def propagate_with_weather(
        self, 
        norad_id: int,
        sample_interval_hours: int = 24
    ) -> pd.DataFrame:
        """
        Generate combined orbital and space weather dataset.
        
        This method:
        1. Retrieves TLEs for the satellite
        2. Retrieves Kp index data
        3. For each TLE epoch, calculates altitude
        4. Joins with closest Kp reading
        5. Computes daily altitude drop
        
        Args:
            norad_id: NORAD catalog ID
            sample_interval_hours: Interval for sampling (default: daily)
            
        Returns:
            DataFrame with columns [Date, Altitude, Kp_Index, Daily_Drop]
        """
        logger.info(f"Propagating orbit for NORAD ID {norad_id}")
        
        # Load TLE data
        with sqlite3.connect(self.db_path) as conn:
            tle_df = pd.read_sql_query(
                """
                SELECT epoch_datetime, tle_line1, tle_line2 
                FROM tle_history 
                WHERE norad_id = ? 
                ORDER BY epoch_datetime ASC
                """,
                conn,
                params=(norad_id,)
            )
            
            kp_df = pd.read_sql_query(
                """
                SELECT time_tag, kp 
                FROM space_weather 
                ORDER BY time_tag ASC
                """,
                conn
            )
        
        if tle_df.empty:
            logger.warning(f"No TLE data found for NORAD ID {norad_id}")
            return pd.DataFrame(columns=['Date', 'Altitude', 'Kp_Index', 'Daily_Drop'])
        
        # Convert timestamps
        tle_df['epoch_datetime'] = pd.to_datetime(tle_df['epoch_datetime'], utc=True)
        
        if not kp_df.empty:
            kp_df['time_tag'] = pd.to_datetime(kp_df['time_tag'], utc=True)
        
        # Vectorized altitude calculation
        results = []
        
        for idx, row in tle_df.iterrows():
            try:
                satellite = self._parse_tle_to_satrec(row['tle_line1'], row['tle_line2'])
                
                if satellite is None:
                    continue
                
                # EXTRACT MEAN ELEMENTS (STABLE PURE DRAG) [NEW]
                # Instead of instantaneous SGP4 propagation (which includes oscillation noise),
                # we use the Mean Motion directly from the TLE logic.
                
                # Constants
                MU = 398600.4418  # Earth Gravitational Parameter (km^3/s^2)
                EARTH_RADIUS_KM = 6378.137
                
                # 1. Get Mean Motion (no_kozai) in radians/minute
                mean_motion_rad_min = satellite.model.no_kozai
                
                # 2. Convert to radians/second
                mean_motion_rad_sec = mean_motion_rad_min / 60.0
                
                # 3. Calculate Semi-Major Axis (km) -> (mu / n^2)^(1/3)
                if mean_motion_rad_sec > 0:
                    semi_major_axis_km = (MU / (mean_motion_rad_sec ** 2)) ** (1/3)
                else:
                    continue
                
                # 4. Calculate Mean Altitude (SMA - Earth Radius)
                # This represents the "average" height, stripping out perigee/apogee noise
                mean_altitude_km = semi_major_axis_km - EARTH_RADIUS_KM
                
                if mean_altitude_km < 0:
                    continue

                # 5. Extract other elements for context
                eccentricity = satellite.model.ecco
                is_circular = eccentricity < 0.01
                
                # Find closest Kp reading
                epoch_dt = row['epoch_datetime'].to_pydatetime()
                kp_value = self._find_closest_kp(epoch_dt, kp_df)
                
                results.append({
                    'Date': epoch_dt.date(),
                    'DateTime': epoch_dt,
                    'SemiMajorAxis': semi_major_axis_km,
                    'Altitude': mean_altitude_km,  # Storing Mean Alt instead of Instantaneous
                    'Eccentricity': eccentricity,
                    'Is_Circular': is_circular,
                    'Kp_Index': kp_value
                })
                
            except Exception as e:
                logger.warning(f"Failed to process TLE at index {idx}: {e}")
                continue
        
        if not results:
            return pd.DataFrame(columns=['Date', 'Altitude', 'Kp_Index', 'Daily_Drop'])
        
        # Create DataFrame
        result_df = pd.DataFrame(results)
        
        # Aggregate to daily values
        daily_df = result_df.groupby('Date').agg({
            'Altitude': 'mean',
            'Kp_Index': 'mean'
        }).reset_index()
        
        # Calculate daily altitude drop (negative change indicates decay)
        daily_df['Daily_Drop'] = daily_df['Altitude'].diff() * -1  # Positive = decay
        
        # First day has no drop (NaN -> 0)
        daily_df['Daily_Drop'] = daily_df['Daily_Drop'].fillna(0)
        
        logger.info(f"Generated {len(daily_df)} daily records for NORAD ID {norad_id}")
        
        return daily_df
    
    def _find_closest_kp(
        self, 
        target_dt: datetime, 
        kp_df: pd.DataFrame
    ) -> Optional[float]:
        """
        Find Kp index value closest to target datetime.
        
        Args:
            target_dt: Target datetime
            kp_df: DataFrame with Kp data (must have time_tag column)
            
        Returns:
            Closest Kp value, or None if no data
        """
        if kp_df.empty:
            return None
        
        try:
            # Ensure target is timezone-aware
            if target_dt.tzinfo is None:
                target_dt = target_dt.replace(tzinfo=timezone.utc)
            
            # Calculate time differences
            time_diffs = abs(kp_df['time_tag'] - target_dt)
            closest_idx = time_diffs.idxmin()
            
            return float(kp_df.loc[closest_idx, 'kp'])
            
        except Exception as e:
            logger.warning(f"Kp lookup failed: {e}")
            return None
    
    def generate_training_dataset(
        self, 
        norad_ids: Optional[List[int]] = None
    ) -> pd.DataFrame:
        """
        Generate combined dataset for all satellites in Golden Dataset.
        
        Args:
            norad_ids: List of NORAD IDs (default: Golden Dataset)
            
        Returns:
            Combined DataFrame with satellite identifier
        """
        if norad_ids is None:
            norad_ids = list(GOLDEN_DATASET.values())
        
        all_data = []
        
        for norad_id in norad_ids:
            df = self.propagate_with_weather(norad_id)
            if not df.empty:
                df['NORAD_ID'] = norad_id
                # Get satellite name
                sat_name = next(
                    (name for name, nid in GOLDEN_DATASET.items() if nid == norad_id),
                    f"NORAD_{norad_id}"
                )
                df['Satellite_Name'] = sat_name
                all_data.append(df)
        
        if not all_data:
            return pd.DataFrame()
        
        combined = pd.concat(all_data, ignore_index=True)
        logger.info(f"Generated training dataset with {len(combined)} records")
        
        return combined


