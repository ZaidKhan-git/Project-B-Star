    def _load_from_txt(self, file_path: str, norad_id: int) -> pd.DataFrame:
        """
        Load TLEs from TXT file (standard 3-line TLE format).
        
        Expected format (each TLE is 3 lines):
        SATELLITE NAME
        1 25544U 98067A   21275.51234567  .00001234  00000-0  12345-4 0  9991
        2 25544  51.6456 123.4567 0001234  12.3456 347.6543 15.48919755123456
        
        Args:
            file_path: Path to TXT file
            norad_id: NORAD catalog ID
            
        Returns:
            DataFrame with TLE data
        """
        records = []
        
        with open(file_path, 'r', encoding='utf-8') as f:
            lines = [line.strip() for line in f.readlines() if line.strip()]
        
        # Process in groups of 3 lines
        i = 0
        while i < len(lines):
            # Check if this looks like a TLE set
            if i + 2 < len(lines):
                line0 = lines[i]      # Satellite name
                line1 = lines[i + 1]  # TLE line 1
                line2 = lines[i + 2]  # TLE line 2
                
                # Validate TLE format (line 1 starts with "1 ", line 2 starts with "2 ")
                if line1.startswith("1 ") and line2.startswith("2 "):
                    # Extract epoch from line 1 (columns 18-32)
                    try:
                        epoch_str = line1[18:32].strip()
                        # Parse TLE epoch format: YYDDD.DDDDDDDD
                        year_2digit = int(epoch_str[:2])
                        day_fraction = float(epoch_str[2:])
                        
                        # Convert 2-digit year (57-99 = 1900s, 00-56 = 2000s)
                        if year_2digit >= 57:
                            year = 1900 + year_2digit
                        else:
                            year = 2000 + year_2digit
                        
                        # Convert day of year to datetime
                        epoch_dt = datetime(year, 1, 1, tzinfo=timezone.utc) + pd.Timedelta(days=day_fraction - 1)
                        
                        records.append({
                            'OBJECT_NAME': line0,
                            'TLE_LINE1': line1,
                            'TLE_LINE2': line2,
                            'EPOCH': epoch_dt.isoformat(),
                            'NORAD_CAT_ID': norad_id
                        })
                        
                        i += 3
                        continue
                        
                    except (ValueError, IndexError) as e:
                        logger.warning(f"Failed to parse TLE at line {i}: {e}")
            
            i += 1
        
        if not records:
            logger.warning(f"No valid TLEs found in {file_path}")
            return pd.DataFrame()
        
        df = pd.DataFrame(records)
        
        # Store to database
        records_stored = self._store_tles(df, norad_id)
        logger.info(f"Loaded and stored {records_stored} TLEs from TXT")
        print(f"    ✓ Loaded {records_stored} TLE records from TXT file")
        
        return df
    
    def _store_tles(self, df: pd.DataFrame, norad_id: int) -> int:
        """
        Store TLE records to SQLite database.
        
        Args:
            df: DataFrame with TLE data from Space-Track or file
            norad_id: NORAD catalog ID
            
        Returns:
            Number of records inserted
        """
        records_inserted = 0
        
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            
            for _, row in df.iterrows():
                try:
                    cursor.execute("""
                        INSERT OR IGNORE INTO tle_history 
                        (norad_id, satellite_name, epoch_datetime, tle_line1, tle_line2,
                         mean_motion, eccentricity, inclination, bstar)
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, (
                        norad_id,
                        row.get('OBJECT_NAME', ''),
                        row.get('EPOCH', ''),
                        row.get('TLE_LINE1', ''),
                        row.get('TLE_LINE2', ''),
                        float(row.get('MEAN_MOTION', 0)) if pd.notna(row.get('MEAN_MOTION')) else 0.0,
                        float(row.get('ECCENTRICITY', 0)) if pd.notna(row.get('ECCENTRICITY')) else 0.0,
                        float(row.get('INCLINATION', 0)) if pd.notna(row.get('INCLINATION')) else 0.0,
                        float(row.get('BSTAR', 0)) if pd.notna(row.get('BSTAR')) else 0.0
                    ))
                    
                    if cursor.rowcount > 0:
                        records_inserted += 1
                        
                except (sqlite3.Error, ValueError) as e:
                    logger.warning(f"Failed to insert TLE record: {e}")
                    
            conn.commit()
        
        return records_inserted
    
    def get_stored_tles(self, norad_id: int) -> pd.DataFrame:
        """
        Retrieve TLEs from local SQLite database.
        
        Args:
            norad_id: NORAD catalog ID
            
        Returns:
            DataFrame with stored TLE history
        """
        with sqlite3.connect(self.db_path) as conn:
            query = """
                SELECT * FROM tle_history 
                WHERE norad_id = ? 
                ORDER BY epoch_datetime ASC
            """
            return pd.read_sql_query(query, conn, params=(norad_id,))
    
    def get_cache_status(self) -> pd.DataFrame:
        """
        Get cache status for all satellites in the database.
        
        Returns:
            DataFrame with NORAD ID, satellite name, and record count
        """
        with sqlite3.connect(self.db_path) as conn:
            query = """
                SELECT 
                    norad_id,
                    satellite_name,
                    COUNT(*) as record_count,
                    MIN(epoch_datetime) as earliest_epoch,
                    MAX(epoch_datetime) as latest_epoch
                FROM tle_history
                GROUP BY norad_id
                ORDER BY norad_id
            """
            return pd.read_sql_query(query, conn)
    
    def fetch_tle_golden_epoch(
        self,
        norad_id: int,
        start_year: int = 2014,
        end_year: int = None,
        force_refresh: bool = False
    ) -> int:
        """
        Fetch TLEs for the "Golden Epoch" (2014-present) using yearly chunks.
        
        Space-Track API times out on large date ranges (11+ years).
        This method fetches year-by-year to avoid timeout.
        
        Args:
            norad_id: NORAD catalog ID
            start_year: First year to fetch (default: 2014)
            end_year: Last year to fetch (default: current year)
            force_refresh: If True, re-download even if cached
            
        Returns:
            Total number of TLE records fetched
        """
        import time
        
        if end_year is None:
            end_year = datetime.now().year
        
        total_records = 0
        
        # Check existing cache first
        if not force_refresh:
            cached_count = self._check_cache(norad_id)
            if cached_count > 0:
                print(f"    [CACHE HIT] Found {cached_count} TLEs for NORAD {norad_id}. Use force_refresh=True to re-download.")
